#!/usr/bin/env python3
"""Writes Sources/PokeTokenBar/Core/Dungeon/BattleForms.generated.swift: every Mega Evolution, Primal Reversion and
Gigantamax variety PokéAPI knows, with the sprites the app can show for it.

Facts only, no names: the app fetches the localized form names at runtime, as for every other form. A variety with no
static sprite is left out; one with no animated sprite is marked so the app shows its still without asking for a GIF.

Run with `python3 -I scripts/generate-battle-forms.py` from the repository root.
"""
import json
import sys
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor

ENDPOINT = "https://graphql.pokeapi.co/v1beta2"
SPRITES = "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon"
OUT = "Sources/PokeTokenBar/Core/Dungeon/BattleForms.generated.swift"
AGENT = {"User-Agent": "PokeTokenBar-battle-data"}


def query(text):
    body = json.dumps({"query": text}).encode()
    request = urllib.request.Request(ENDPOINT, data=body, headers={"Content-Type": "application/json", **AGENT})
    with urllib.request.urlopen(request, timeout=180) as response:
        data = json.load(response)
    if "errors" in data:
        sys.exit(json.dumps(data["errors"]))
    return data["data"]


def exists(url):
    request = urllib.request.Request(url, method="HEAD", headers=AGENT)
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return response.status == 200
    except urllib.error.HTTPError:
        return False


def main():
    rows = query("""{ pokemon(where: {name: {_regex: "-(mega|mega-x|mega-y|mega-z|gmax|primal)$"}}, order_by: {id: asc}) {
        id name pokemon_species_id
        pokemonforms { id }
        pokemonspecy { name is_legendary is_mythical }
    } }""")["pokemon"]

    def sprites(row):
        return exists(f"{SPRITES}/{row['id']}.png"), exists(f"{SPRITES}/other/showdown/{row['id']}.gif")

    with ThreadPoolExecutor(max_workers=12) as pool:
        found = list(pool.map(sprites, rows))

    lines = []
    for row, (still, animated) in zip(rows, found):
        if not still:
            print(f"left out, no sprite: {row['name']}", file=sys.stderr)
            continue
        species = row["pokemonspecy"]["name"]
        form = row["name"][len(species) + 1:] if row["name"].startswith(species + "-") else row["name"]
        kind = "gigantamax" if form.endswith("gmax") else "primal" if form.endswith("primal") else "mega"
        legendary = row["pokemonspecy"]["is_legendary"] or row["pokemonspecy"]["is_mythical"]
        form_id = row["pokemonforms"][0]["id"]
        lines.append(f'{row["id"]}|{row["pokemon_species_id"]}|{form}|{form_id}|{kind}|{int(legendary)}|{int(animated)}')

    with open(OUT, "w", encoding="utf-8") as out:
        out.write("// Generated by scripts/generate-battle-forms.py from PokéAPI. Do not edit.\n")
        out.write("// pokemonID|speciesID|form|formID|kind|legendary|animated\n\n")
        out.write("extension BattleForms {\n    static let table = \"\"\"\n")
        out.write("\n".join(lines))
        out.write("\n\"\"\"\n}\n")
    print(f"{len(lines)} battle forms written to {OUT}")


if __name__ == "__main__":
    main()
