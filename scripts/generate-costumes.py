#!/usr/bin/env python3
"""Writes Sources/PokeTokenBar/Core/Costumes.generated.swift: every costumed Pokémon of Pokémon GO that PokeMiners
has an image of, and the month of the year its costume comes back in (the owner, 2026-11-13: "la collection qui se
renouvelle", one lot a month, back every year).

Facts only: the species, its form when the costume is on one (Galarian Zigzagoon, a Pumpkaboo's size), the costume's
code. The images are PokeMiners' 256 px icons, read at runtime (`CostumeCatalog.spriteURL`); a costume whose code is
not in `MONTHS` stops the script, so a new one of Pokémon GO is given its month before it ships.

Run with `python3 -I scripts/generate-costumes.py` from the repository root (it reads GitHub's API: `GITHUB_TOKEN`
in the environment lifts its rate limit).
"""
import json
import os
import re
import sys
import urllib.request

REPO = "https://api.github.com/repos/PokeMiners/pogo_assets"
FOLDER = "Images/Pokemon - 256x256"
OUT = "Sources/PokeTokenBar/Core/Costumes.generated.swift"
AGENT = {"User-Agent": "PokeTokenBar-costumes", "Accept": "application/vnd.github+json"}
if os.environ.get("GITHUB_TOKEN"):
    AGENT["Authorization"] = "Bearer " + os.environ["GITHUB_TOKEN"]

# The month each costume comes back in: its event's season in Pokémon GO.
MONTHS = {
    1: ["JAN_2020_NOEVOLVE", "JAN_2022_NOEVOLVE", "JAN_2023_NOEVOLVE", "JAN_2024"],
    2: ["FEB_2019", "GEMS_1_2021_NOEVOLVE", "GEMS_2_2021_NOEVOLVE", "KANTO_2020_NOEVOLVE", "JOHTO_2020_NOEVOLVE",
        "HOENN_2020_NOEVOLVE", "SINNOH_2020_NOEVOLVE", "GOTOUR_2023_BANDANA", "GOTOUR_2023_BANDANA_NOEVOLVE",
        "GOTOUR_2023_HAT", "GOTOUR_2023_HAT_NOEVOLVE"],
    3: ["PI", "PI_NOEVOLVE", "SPRING_2023", "SPRING_2023_INSTINCT", "SPRING_2023_MYSTIC", "SPRING_2023_VALOR"],
    4: ["APRIL_2020_NOEVOLVE", "SPRING_2020_NOEVOLVE", "SPRING_2024"],
    5: ["MAY_2019_NOEVOLVE", "MAY_2023"],
    6: ["GOFEST_2021_NOEVOLVE", "GOFEST_2022_NOEVOLVE", "SAFARI_2020_NOEVOLVE"],
    7: ["ANNIVERSARY", "ONE_YEAR_ANNIVERSARY", "ANNIVERSARY_2022_NOEVOLVE", "ANNIVERSARY_2024"],
    8: ["SUMMER_2018", "SUMMER_2024", "INDONESIA_2025_NOEVOLVE", "HORIZONS_2025_NOEVOLVE"],
    9: ["FASHION_2021_NOEVOLVE", "FASHION_2025", "TCG_2022_NOEVOLVE", "ROYAL_NOEVOLVE", "COSTUME_1", "COSTUME_2"],
    10: ["HALLOWEEN_2017", "HALLOWEEN_2021_NOEVOLVE", "HALLOWEEN_2025", "FALL_2018", "FALL_2020_NOEVOLVE", "FALL_2022",
         "FALL_2022_NOEVOLVE", "FALL_2023", "FALL_2023_NOEVOLVE", "FALL_2024"],
    11: ["NOVEMBER_2018", "NIGHTCAP"],
    12: ["HOLIDAY_2016", "HOLIDAY_2021_NOEVOLVE", "HOLIDAY_2022", "HOLIDAY_2023", "WINTER_2018", "WINTER_2024"],
}
# PokeMiners' form codes, as the app names the forms (`PokemonForm`).
FORMS = {"GALARIAN": "galar", "AVERAGE": "average", "SMALL": "small", "LARGE": "large", "SUPER": "super"}
NAME = re.compile(r"Addressable Assets/pm(\d+)\.(?:f([A-Z0-9_]+)\.)?c([A-Z0-9_]+)\.icon\.png$")


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=AGENT), timeout=120) as response:
        return json.load(response)


def main():
    folder = next(item for item in get(f"{REPO}/contents/Images") if item["name"] == FOLDER.split("/")[1])
    tree = get(f"{REPO}/git/trees/{folder['sha']}?recursive=1")
    if tree.get("truncated"):
        sys.exit("the listing was truncated")
    month_of = {code: month for month, codes in MONTHS.items() for code in codes}
    entries = set()
    for item in tree["tree"]:
        match = NAME.match(item["path"])
        if not match:
            continue
        species, form, code = int(match.group(1)), match.group(2), match.group(3)
        if code not in month_of:
            sys.exit(f"no month for the costume {code}: add it to MONTHS")
        if form is not None and form not in FORMS:
            sys.exit(f"no app form for {form} (#{species}, {code}): add it to FORMS")
        entries.add((month_of[code], code, species, FORMS.get(form) if form else None))
    unused = set(month_of) - {code for _, code, _, _ in entries}
    if unused:
        sys.exit(f"costumes without an image: {sorted(unused)}")
    lines = [
        "// Generated by scripts/generate-costumes.py from PokeMiners/pogo_assets. Do not edit.",
        "",
        "extension CostumeCatalog {",
        "    /// Every costumed Pokémon PokeMiners has an image of, by month, then costume, species and form.",
        "    static let entries: [CostumeEntry] = [",
    ]
    for month, code, species, form in sorted(entries, key=lambda e: (e[0], e[1], e[2], e[3] or "")):
        form_text = f', form: "{form}"' if form else ""
        lines.append(f'        .init("{code}", {species}{form_text}, month: {month}),')
    lines += ["    ]", "}", ""]
    with open(OUT, "w") as out:
        out.write("\n".join(lines))
    print(f"{len(entries)} costumed Pokémon written to {OUT}")


if __name__ == "__main__":
    main()
