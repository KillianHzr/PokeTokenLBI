import Foundation

/// A move's side of the damage formula: physical against Defense, special against Special Defense, or no damage.
enum MoveClass: String, Sendable, Codable {
    case physical, special, status
}

/// The six stats a battle reads, and the two it only stages.
enum BattleStat: String, Sendable, Codable, CaseIterable {
    case attack, defense, specialAttack = "special-attack", specialDefense = "special-defense", speed, accuracy, evasion
}

/// A status condition, as PokéAPI's move meta names them. `none` and the effects the engine reads elsewhere (a trap,
/// Leech Seed, Yawn, confusion) are kept apart from the five lasting ones.
enum BattleAilment: String, Sendable, Codable {
    case paralysis, sleep, freeze, burn, poison, confusion, trap, leechSeed = "leech-seed", yawn, badPoison
}

/// What PokéAPI's move meta category says a move does, which tells whose stats its changes touch.
enum MoveMetaCategory: String, Sendable {
    case damage, ailment, netGoodStats = "net-good-stats", heal, damageAilment = "damage-ailment", swagger
    case damageLower = "damage-lower", damageRaise = "damage-raise", damageHeal = "damage-heal", ohko
    case wholeFieldEffect = "whole-field-effect", fieldEffect = "field-effect", forceSwitch = "force-switch", unique
}

/// One move's battle data, from `BattleDataTables.moves` (PokéAPI, generated by `scripts/generate-battle-data.py`).
struct BattleMove: Sendable, Equatable {
    let slug: String
    let type: PokemonType
    let moveClass: MoveClass
    /// 0 for a move whose damage is not set by a power (status, fixed damage, OHKO).
    let power: Int
    /// 0 never misses.
    let accuracy: Int
    let priority: Int
    /// PokéAPI's target: `selected-pokemon`, `all-opponents`, `all-other-pokemon`, `user`, `users-field`...
    let target: String
    let effectChance: Int
    let ailment: BattleAilment?
    let ailmentChance: Int
    /// Critical-hit stages the move adds.
    let critStage: Int
    /// Percent of the damage dealt the user regains, negative for recoil.
    let drain: Int
    /// Percent of the user's maximum HP it regains, negative for the HP it costs.
    let healing: Int
    let flinchChance: Int
    let minHits: Int
    let maxHits: Int
    let minTurns: Int
    let maxTurns: Int
    let statChance: Int
    let statChanges: [StatChange]
    let category: MoveMetaCategory
    let flags: Set<String>

    struct StatChange: Sendable, Equatable {
        let stat: BattleStat
        let change: Int
    }

    var isDamaging: Bool { moveClass != .status }
    var isContact: Bool { flags.contains("contact") }
    var charges: Bool { flags.contains("charge") }
    var recharges: Bool { flags.contains("recharge") }
    var isSound: Bool { flags.contains("sound") }
    var isPunch: Bool { flags.contains("punch") }
    var isBite: Bool { flags.contains("bite") }
    var isPulse: Bool { flags.contains("pulse") }
    /// PokéAPI's name for the ball and bomb moves Bulletproof stops.
    var isBallistic: Bool { flags.contains("ballistics") }
    var isPowder: Bool { flags.contains("powder") }
    /// Its type for this Pokémon, as the games give it: Hidden Power's from its IVs; Judgment and Multi-Attack its
    /// form's (a Plate's, a Memory's), Raging Bull and Ivy Cudgel its breed's or mask's, Techno Blast its Drive's,
    /// Revelation Dance its first type. The others keep theirs.
    func type(for spec: BattlerSpec) -> PokemonType {
        type(types: spec.types, form: spec.form, hiddenPower: spec.hiddenPowerType)
    }

    func type(types: [PokemonType], form: PokemonForm?, hiddenPower: PokemonType?) -> PokemonType {
        switch slug {
        case "hidden-power": return hiddenPower ?? type
        case "judgment", "multi-attack", "revelation-dance": return types.first ?? type
        case "raging-bull", "ivy-cudgel": return types.last ?? type
        case "techno-blast":
            return ["douse": .water, "shock": .electric, "burn": .fire, "chill": .ice][form?.rawValue ?? ""] ?? type
        default: return type
        }
    }

    /// The moves whose type is their own whatever Normalize says.
    static let typeKeptUnderNormalize: Set<String> = ["hidden-power", "weather-ball", "natural-gift", "judgment",
                                                      "techno-blast", "multi-attack", "terrain-pulse"]

    /// Showdown's flags (2026-11-03): PokéAPI has neither.
    var isSlicing: Bool { flags.contains("slicing") }
    var isWind: Bool { flags.contains("wind") }
    /// Protect stops it: its "protect" flag, PokéAPI's or Showdown's. Every move but the Z-Moves has Showdown's, so a move
    /// without it goes through, as Future Sight does (2026-11-04).
    var isBlockedByProtect: Bool { flags.contains("protect") }
    /// Sound moves and those PokéAPI marks "authentic" go through a substitute.
    var bypassesSubstitute: Bool { isSound || flags.contains("authentic") }
    var hasSecondaryEffect: Bool {
        effectChance > 0 && (ailmentChance > 0 || flinchChance > 0 || statChance > 0)
    }

    /// Hits every opponent on the field (at 75% when more than one stands).
    var hitsAllOpponents: Bool { target == "all-opponents" || target == "all-other-pokemon" }
    /// Lands on its user or its user's side, never on a foe.
    var targetsOwnSide: Bool {
        ["user", "users-field", "user-and-allies", "user-or-ally", "ally", "all-allies"].contains(target)
    }

    /// Whether the engine plays this move: every damaging move, and the status moves it knows. The others are
    /// skipped in a loop at no cost.
    var hasEffect: Bool {
        if isDamaging || BattleSimulation.handledStatusMoves.contains(slug) { return true }
        switch BattleSimulation.statusKind(self) {
        case .heal, .netGoodStats: return true
        case .ailment, .swagger: return ailment != nil
        default: return false
        }
    }

    /// Z-Moves and Max Moves: the app has no crystal nor band, so no loop holds them and no move calls them
    /// (the owner, 2026-11-03).
    var isZOrMax: Bool {
        slug.hasSuffix("--physical") || slug.hasSuffix("--special") || slug.hasPrefix("max-") || slug.hasPrefix("g-max-")
            || Self.zSignatures.contains(slug)
    }

    static let zSignatures: Set<String> = [
        "catastropika", "sinister-arrow-raid", "malicious-moonsault", "oceanic-operetta", "guardian-of-alola",
        "soul-stealing-7-star-strike", "stoked-sparksurfer", "pulverizing-pancake", "extreme-evoboost",
        "genesis-supernova", "10-000-000-volt-thunderbolt", "light-that-burns-the-sky", "searing-sunraze-smash",
        "menacing-moonraze-maelstrom", "lets-snuggle-forever", "splintered-stormshards", "clangorous-soulblaze",
    ]

    /// Offensive moves of 100 power or more are locked until a Technical Capsule unlocks them (validated 2026-10-30),
    /// and so are the moves whose effect does not come from their user's stats (the owner, 2026-11-03: "ce genre
    /// d'attaques doivent être bloquées dans les gains de donjon rares").
    var isLocked: Bool { isDamaging && power >= 100 || Self.rareMoves.contains(slug) }

    static let rareMoves: Set<String> = [
        "curse", "nightmare", "perish-song", "destiny-bond", "guillotine", "horn-drill", "fissure", "sheer-cold",
        "super-fang", "natures-madness", "ruination", "endeavor", "pain-split", "final-gambit", "counter", "mirror-coat",
        "metal-burst", "comeuppance", "bide",
    ]

    /// The time a move takes to cast before speed, in milliseconds (R1): priority moves are quick, status moves short,
    /// the stronger the slower, and a charge or a recharge adds two seconds.
    var castBase: Int {
        var base: Int
        if priority > 0 {
            base = 800
        } else if !isDamaging {
            base = 1200
        } else {
            switch power {
            case ...60: base = 1500
            case 61...90: base = 2200
            case 91...120: base = 3000
            default: base = 3800
            }
        }
        if charges || recharges { base += 2000 }
        return base
    }
}

/// The moves' table, parsed once from the generated text.
enum MoveTable {
    static let all: [String: BattleMove] = {
        var table: [String: BattleMove] = [:]
        for line in BattleDataTables.moves.split(separator: "\n") {
            guard let move = parse(line) else { continue }
            table[move.slug] = move
        }
        return table
    }()

    static func move(_ slug: String) -> BattleMove? { all[slug] }

    private static func parse(_ line: Substring) -> BattleMove? {
        let f = line.split(separator: "|", omittingEmptySubsequences: false).map(String.init)
        guard f.count >= 22, let type = PokemonType(rawValue: f[1]), let moveClass = MoveClass(rawValue: f[2]) else {
            return nil
        }
        func int(_ i: Int) -> Int { Int(f[i]) ?? 0 }
        let ailment: BattleAilment? = switch f[8] {
        case "none", "unknown", "": nil
        default: BattleAilment(rawValue: f[8])
        }
        let changes = f[19].split(separator: ",").compactMap { pair -> BattleMove.StatChange? in
            let parts = pair.split(separator: ":")
            guard parts.count == 2, let stat = BattleStat(rawValue: String(parts[0])), let change = Int(parts[1]) else {
                return nil
            }
            return BattleMove.StatChange(stat: stat, change: change)
        }
        let move = BattleMove(slug: f[0], type: type, moveClass: moveClass, power: int(3), accuracy: int(4),
                              priority: int(5), target: f[6], effectChance: int(7), ailment: ailment,
                              ailmentChance: int(9), critStage: int(10), drain: int(11), healing: int(12),
                              flinchChance: int(13), minHits: int(14), maxHits: int(15), minTurns: int(16),
                              maxTurns: int(17), statChance: int(18), statChanges: changes,
                              category: MoveMetaCategory(rawValue: f[20]) ?? .unique,
                              flags: Set(f[21].split(separator: ",").map(String.init)))
        return RecentMoveEffect.all[move.slug].map(move.completed) ?? move
    }
}

/// One Pokémon variety's battle data (`BattleDataTables.species`), keyed by its PokéAPI id
/// (`PokemonForm.detailsID`).
struct SpeciesBattleData: Sendable, Equatable {
    let pokemonID: Int
    let speciesID: Int
    /// HP, Attack, Defense, Special Attack, Special Defense, Speed.
    let baseStats: [Int]
    let types: [PokemonType]
    /// Its abilities in slot order; a hidden one is marked.
    let abilities: [(slug: String, hidden: Bool)]
    /// The four moves a wild one or a boss loops.
    let loop: [String]
    /// The moves a player's suggestion picks from (`MoveSuggester`): each type's strongest under 100 power and at 100
    /// or more, the best setup, recovery and status moves.
    let pool: [String]
    /// In hectograms, as PokéAPI gives it: what Low Kick, Grass Knot, Heavy Slam and Heat Crash weigh.
    var weight = 0

    static func == (lhs: SpeciesBattleData, rhs: SpeciesBattleData) -> Bool { lhs.pokemonID == rhs.pokemonID }
}

enum SpeciesBattleTable {
    static let all: [Int: SpeciesBattleData] = {
        var table: [Int: SpeciesBattleData] = [:]
        for line in BattleDataTables.species.split(separator: "\n") {
            let f = line.split(separator: "|", omittingEmptySubsequences: false).map(String.init)
            guard f.count >= 7, let id = Int(f[0]), let species = Int(f[1]) else { continue }
            let stats = f[2].split(separator: ",").compactMap { Int($0) }
            guard stats.count == 6 else { continue }
            let abilities = f[4].split(separator: ",").map { slug -> (slug: String, hidden: Bool) in
                slug.hasSuffix("*") ? (String(slug.dropLast()), true) : (String(slug), false)
            }
            table[id] = SpeciesBattleData(pokemonID: id, speciesID: species, baseStats: stats,
                                          types: f[3].split(separator: ",").compactMap { PokemonType(rawValue: String($0)) },
                                          abilities: abilities, loop: f[5].split(separator: ",").map(String.init),
                                          pool: f[6].split(separator: ",").map(String.init),
                                          weight: f.count > 7 ? Int(f[7]) ?? 0 : 0)
        }
        return table
    }()

    /// A species in a form, or its default variety when the form has no data of its own.
    static func data(speciesID: Int, form: PokemonForm? = nil) -> SpeciesBattleData? {
        all[PokemonForm.detailsID(speciesID: speciesID, form: form)] ?? all[speciesID]
    }
}

/// One species' facts from `BattleDataTables.speciesInfo`: its capture rate, whether it is an unbreedable legendary
/// or mythical (`BaseSpecies.isUnbreedableLegendary`), the species it evolves from and its generation.
struct SpeciesInfo: Sendable, Equatable {
    let id: Int
    let captureRate: Int
    let isLegendary: Bool
    let evolvesFrom: Int?
    let generation: Int
    /// Female eighths, -1 genderless; nil from a table generated before it was there.
    var genderRate: Int? = nil

    static let all: [Int: SpeciesInfo] = {
        var table: [Int: SpeciesInfo] = [:]
        for line in BattleDataTables.speciesInfo.split(separator: "\n") {
            let f = line.split(separator: "|").compactMap { Int($0) }
            guard f.count >= 5 else { continue }
            table[f[0]] = SpeciesInfo(id: f[0], captureRate: f[1], isLegendary: f[2] == 1,
                                      evolvesFrom: f[3] == 0 ? nil : f[3], generation: f[4],
                                      genderRate: f.count > 5 ? f[5] : nil)
        }
        return table
    }()

    /// The first species of its line.
    static func baseID(of id: Int) -> Int {
        var current = id
        var seen: Set<Int> = []
        while let parent = all[current]?.evolvesFrom, !seen.contains(parent) {
            seen.insert(current)
            current = parent
        }
        return current
    }

    /// The line's rarity, as the eggs and the Pokédex read it: its first species' (`BaseSpecies.rarity`).
    static func lineRarity(of id: Int) -> Rarity {
        guard let base = all[baseID(of: id)] else { return .common }
        return BaseSpecies(id: base.id, captureRate: base.captureRate, isLegendary: base.isLegendary).rarity
    }

    private static let parents = Set(all.values.compactMap(\.evolvesFrom))

    /// Whether nothing evolves from it.
    static func isFinal(_ id: Int) -> Bool { !parents.contains(id) }
}
